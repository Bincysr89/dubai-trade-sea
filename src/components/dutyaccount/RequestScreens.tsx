/* ── e-Payment: Confirm Payment → redirect/processing → paid ── */
export function PaymentFlow({ amount, onPaid, onCancel }: { amount: string; onPaid: () => void; onCancel: () => void }) {
  const [processing, setProcessing] = useState(false);
  const paidRef = useRef(onPaid);
  paidRef.current = onPaid;
  useEffect(() => {
    if (!processing) return;
    const t = setTimeout(() => paidRef.current(), 1600);
    return () => clearTimeout(t);
  }, [processing]);

  if (processing) {
    return (
      <Overlay z={500}>
        <div role="alertdialog" aria-modal="true" aria-label="Processing payment"
          className="bg-white rounded-[12px] flex flex-col items-center gap-[20px] px-[40px] py-[40px] max-w-[460px] w-full"
          style={{ boxShadow: '0px 8px 40px rgba(0,0,0,0.18)' }}>
          <svg width="64" height="64" viewBox="0 0 50 50" aria-hidden>
            <circle cx="25" cy="25" r="20" fill="none" stroke="#e2ebf9" strokeWidth="5" />
            <circle cx="25" cy="25" r="20" fill="none" stroke="#1360d2" strokeWidth="5" strokeLinecap="round" strokeDasharray="90 150">
              <animateTransform attributeName="transform" type="rotate" from="0 25 25" to="360 25 25" dur="0.9s" repeatCount="indefinite" />
            </circle>
          </svg>
          <p className="text-[20px] text-[#0e1b3d] text-center" style={{ fontWeight: 700 }}>ePayment Processing</p>
          <p className="text-[16px] text-[#697498] text-center">Completing your payment through the Dubai E-Government payment site. Please do not close this window.</p>
        </div>
      </Overlay>
    );
  }
  return (
    <Modal
      title="Confirm Payment"
      width={760}
      onClose={onCancel}
      footer={(
        <>
          <SecondaryButton onClick={onCancel}>Cancel</SecondaryButton>
          <PrimaryButton onClick={() => setProcessing(true)}>
            <svg viewBox="0 0 20 20" width="18" height="18" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round"><path d="M4 10.5l4 4 8-9" /></svg>
            Confirm
          </PrimaryButton>
        </>
      )}
    >
      <SubHeading>Confirm Transaction</SubHeading>
      <InfoBanner tone="info">
        By clicking the confirm button, you are authorizing us to redirect your request for payment of{' '}
        <strong className="inline-flex items-baseline gap-[3px]"><Dh /> {amount}</strong> through Dubai E-Government payment site.
      </InfoBanner>
    </Modal>
  );
}

