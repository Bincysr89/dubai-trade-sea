/* ── Withdraw a submitted request: remarks page → success ── */
export function WithdrawRequestPage({ request: r, onBack, onHome, onWithdrawn }: {
  request: AccountRequest;
  onBack: () => void;
  onHome: () => void;
  onWithdrawn: (remarks: string) => void;
}) {
  const a = findAccount(r.accountNo);
  const g = r.guarantee;
  const [remarks, setRemarks] = useState('');
  const [done, setDone] = useState(false);

  const info: [string, React.ReactNode][] = g
    ? [
        ['Request Number', r.requestNo],
        ['Guarantee Type', g.type],
        ['Existing Amount', <Amount value={g.existing} />],
        ['Proposed Amount', <Amount value={g.proposed} />],
        ['Request Date', r.requestDate],
      ]
    : [
        ['Request Number', r.requestNo],
        ['Request Type', r.requestType],
        ['Request Status', <StatusChip status={r.status} />],
        ['Request Date', r.requestDate],
      ];

  if (done) {
    return (
      <PageShell
        title="Withdraw Request"
        badge={`Request ${r.requestNo}`}
        crumbs={[{ label: 'Duty Account', onClick: onBack }, { label: 'Request Withdrawn' }]}
        onHome={onHome}
        resultPage
      >
        <ResultCard
          heading={g ? 'Your Guarantee Request Has Been Successfully Withdrawn' : `Your ${r.requestType} Request Has Been Successfully Withdrawn`}
          message="The request status is now Withdrawn. The withdrawal is recorded in the request's Audit History."
          details={g
            ? [
                ['Request No.', r.requestNo],
                ['Guarantee Type', g.type],
                ['Existing Amount', <Amount value={g.existing} />],
                ['Proposed Amount', <Amount value={g.proposed} />],
              ]
            : [
                ['Request No.', r.requestNo],
                ['Request Type', r.requestType],
                ['Account', `${r.accountNo} - ${r.accountName}`],
              ]}
          actions={<PrimaryButton onClick={onBack}>Back to Listing</PrimaryButton>}
        />
      </PageShell>
    );
  }

  return (
    <PageShell
      title="Withdraw Request"
      badge={`Request ${r.requestNo}`}
      crumbs={[{ label: 'Duty Account', onClick: onBack }, { label: 'Withdraw Request' }]}
      onHome={onHome}
      onBackToListing={onBack}
      rightContent={(
        <div className="flex items-center gap-[12px]">
          <SecondaryButton onClick={onBack}>Cancel</SecondaryButton>
          <PrimaryButton onClick={() => { onWithdrawn(remarks.trim() || 'Withdrawn by user'); setDone(true); }}>Submit</PrimaryButton>
        </div>
      )}
    >
      <Section title="Account Information">
        <InfoGrid items={[
          ['Account', `${r.accountNo} - ${r.accountName}`],
          ['Account Holder Type', a?.holderType ?? '—'],
          ['Account Holder Code', a?.holderCode ?? '—'],
          ['Account Type', r.accountType],
        ]} />
      </Section>
      <Section title={g ? 'Guarantee Information' : 'Request Information'}>
        <InfoGrid items={info} />
        <div className="mt-[24px] grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-[24px]">
          <FloatField label="Remarks" required value={remarks} placeholder="Reason for withdrawing this request"
            onChange={setRemarks} />
        </div>
      </Section>
    </PageShell>
  );
}

/* ── Audit history (same table template as the Refund & Claims audit history) ── */
const AUDIT_COLS = [
  { label: 'Action Date', w: 180 },
  { label: 'Request No.', w: 130 },
  { label: 'Request Type', w: 200 },
  { label: 'Action', w: 190 },
  { label: 'Performed By', w: 160 },
  { label: 'Remarks', w: 260 },
];
const AUDIT_STATUS_W = 170;

export function RequestAuditHistoryPage({ request: r, onBack, onHome }: { request: AccountRequest; onBack: () => void; onHome: () => void }) {
  const { scrollRef, atScrollStart, atScrollEnd, handleScroll, scrollToStart, scrollToEnd } = useTableBehaviors();
  const rows = [...r.history].reverse();
  const cell = (content: React.ReactNode, w: number, first = false) => (
    <td style={{ background: '#fff', padding: '0 12px', paddingLeft: first ? 16 : 12, height: 60, verticalAlign: 'middle', width: w, borderBottom: '1px solid #f8f8f8' }}>
      {content}
    </td>
  );
  const txt = (v: string) => <span className="text-[16px] text-[#0e1b3d] whitespace-nowrap">{v}</span>;

  return (
    <PageShell
      title="Audit History"
      badge={`Request ${r.requestNo}`}
      crumbs={[{ label: 'Duty Account', onClick: onBack }, { label: 'Audit History' }]}
      onHome={onHome}
      onBack={onBack}
    >
      <div style={{ position: 'relative' }}>
        <ScrollArrows atStart={atScrollStart} atEnd={atScrollEnd} onLeft={scrollToStart} onRight={scrollToEnd} stickyWidth={AUDIT_STATUS_W} />
        <div ref={scrollRef} onScroll={handleScroll} className="overflow-x-auto">
          <table className="w-full" style={{ minWidth: 1300, borderCollapse: 'separate', borderSpacing: '0 8px', fontFamily: font }}>
            <thead>
              <tr>
                {AUDIT_COLS.map((c, i) => (
                  <th key={c.label} style={{ width: c.w, minWidth: c.w, background: '#a6c2e9', padding: '10px 12px', paddingLeft: i === 0 ? 16 : 12, textAlign: 'left', fontWeight: 500, borderRadius: i === 0 ? '8px 0 0 8px' : undefined }}>
                    <ColumnFilter label={c.label} labelClass="text-[16px] font-medium text-[#051937]" />
                  </th>
                ))}
                <th style={{ position: 'sticky', right: 0, width: AUDIT_STATUS_W, minWidth: AUDIT_STATUS_W, background: '#a6c2e9', padding: '10px 12px', textAlign: 'left', fontWeight: 500, zIndex: 2, borderRadius: '0 8px 8px 0', boxShadow: '-3px 0 6px rgba(0,0,0,0.06)' }}>
                  <ColumnFilter label="Status" labelClass="text-[16px] font-medium text-[#051937]" />
                </th>
              </tr>
            </thead>
            <tbody>
              {rows.map((h, i) => (
                <tr key={i}>
                  {cell(txt(h.date), 180, true)}
                  {cell(txt(r.requestNo), 130)}
                  {cell(txt(r.requestType), 200)}
                  {cell(<span className="text-[16px] text-[#0e1b3d]" style={{ fontWeight: 500 }}>{h.action}</span>, 190)}
                  {cell(txt(h.by), 160)}
                  {cell(<span className="text-[16px] text-[#0e1b3d] block whitespace-normal" style={{ lineHeight: 1.3 }}>{h.remarks || '—'}</span>, 260)}
                  <td style={{ position: 'sticky', right: 0, background: '#fff', padding: '0 12px', height: 60, verticalAlign: 'middle', width: AUDIT_STATUS_W, borderBottom: '1px solid #f8f8f8', zIndex: 1, boxShadow: '-3px 0 6px rgba(0,0,0,0.06)' }}>
                    <StatusChip status={h.status} />
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    </PageShell>
  );
}
